#!/usr/bin/env node
/**
 * The portfolio contract gate.
 *
 * The portfolio API is owned by backend-apis, which generates
 * `contracts/universe-portfolio-openapi.json` from the same tables the
 * service answers with and fails its own build when the two disagree.
 * This repository consumes that API through handwritten TypeScript
 * interfaces, and handwritten interfaces are exactly where a contract
 * quietly stops being true: a field is renamed upstream, the interface
 * keeps the old name, and every read of it is undefined at runtime while
 * the compiler stays perfectly happy.
 *
 * So this pins a copy of the document and holds the interfaces to it.
 *
 *   --record --from <url|file>   pin a contract document
 *   --check                      the offline gate CI runs on every commit
 *
 * `--check` never reaches the network. For every schema it is asked to
 * hold, it compares the property names the contract defines against the
 * property names the matching interface declares, in both directions: a
 * field the contract has and the interface lacks is a field this
 * repository cannot read, and a field the interface has and the contract
 * does not is a field nobody will ever send.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

export const PORTFOLIO_SCHEMA_VERSION = 'universe-portfolio-v1';
export const SOURCE_REPOSITORY = 'bitcoinuniverseio/backend-apis';

const REPOSITORY_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
  '..',
);
const PINNED_PATH = path.join(
  REPOSITORY_ROOT,
  'docs',
  'protocols',
  'PORTFOLIO-CONTRACT.json',
);
const TYPES_PATH = path.join(
  REPOSITORY_ROOT,
  'frontend',
  'src',
  'app',
  'universe',
  'portfolio',
  'portfolio.types.ts',
);

/**
 * Which contract schema each interface implements.
 *
 * Only the shapes this repository actually reads field by field are held.
 * A schema the interface deliberately narrows is listed with the fields
 * it is allowed to omit, so the exemption is written down rather than
 * being an absence nobody notices.
 */
export const HELD_SCHEMAS = [
  {
    schema: 'AssetIdentity',
    interface: 'PortfolioAssetIdentity',
    mayOmit: [],
  },
  {
    schema: 'Checkpoint',
    interface: 'PortfolioCheckpoint',
    mayOmit: [],
  },
  {
    schema: 'PriceObservation',
    interface: 'PortfolioPriceObservation',
    mayOmit: [],
  },
  {
    schema: 'Holding',
    interface: 'PortfolioHolding',
    // The interface carries `identity` in place of repeating its parts.
    mayOmit: [],
  },
  {
    schema: 'SourceReport',
    interface: 'PortfolioSourceReport',
    mayOmit: [],
  },
  {
    schema: 'ProtocolStatement',
    interface: 'PortfolioProtocolStatement',
    mayOmit: [],
  },
  {
    schema: 'EvidenceEnvelope',
    interface: 'PortfolioEvidenceEnvelope',
    mayOmit: [],
  },
  {
    schema: 'ValuationCoverage',
    interface: 'PortfolioValuationCoverage',
    mayOmit: [],
  },
];

function fail(message) {
  process.stderr.write(`${message}\n`);
  process.exitCode = 1;
}

/** Reads a document from a file path or an http(s) URL. */
async function readDocument(source) {
  if (/^https?:\/\//.test(source)) {
    const response = await fetch(source, {
      headers: { accept: 'application/json' },
    });
    if (!response.ok) {
      throw new Error(`${source} answered ${response.status}`);
    }
    return JSON.parse(await response.text());
  }
  return JSON.parse(await readFile(source, 'utf8'));
}

/**
 * The property names one exported interface declares.
 *
 * Deliberately small: the file is generated by hand in a house style and
 * a full TypeScript parse would be more machinery than the question
 * needs. It reads the body between the interface header and its closing
 * brace at column zero, and takes the identifier before each colon at
 * one level of nesting.
 */
export function interfaceProperties(source, name) {
  const header = new RegExp(`^export interface ${name} \\{$`, 'm');
  const start = source.search(header);
  if (start === -1) return null;
  const bodyStart = source.indexOf('\n', start) + 1;
  const end = source.indexOf('\n}', bodyStart);
  if (end === -1) return null;
  const body = source.slice(bodyStart, end);
  const names = new Set();
  let depth = 0;
  for (const rawLine of body.split('\n')) {
    const line = rawLine.trim();
    if (!line || line.startsWith('//') || line.startsWith('*') || line.startsWith('/*')) {
      continue;
    }
    if (depth === 0) {
      const match = /^readonly\s+([A-Za-z_][A-Za-z0-9_]*)\??\s*:/.exec(line);
      if (match) names.add(match[1]);
    }
    depth += (line.match(/\{/g) ?? []).length;
    depth -= (line.match(/\}/g) ?? []).length;
    if (depth < 0) depth = 0;
  }
  return names;
}

/** The property names one contract schema defines. */
export function schemaProperties(document, name) {
  const schema = document?.components?.schemas?.[name];
  if (!schema || typeof schema !== 'object') return null;
  const properties = schema.properties;
  if (!properties || typeof properties !== 'object') return null;
  return new Set(Object.keys(properties));
}

/** Holds the pinned document to its own shape and provenance. */
export function validateDocument(document) {
  const problems = [];
  if (typeof document?.openapi !== 'string') {
    problems.push('the document names no openapi version');
  }
  if (document?.info?.version !== PORTFOLIO_SCHEMA_VERSION) {
    problems.push(
      `the document names version ${String(document?.info?.version)}, not ${PORTFOLIO_SCHEMA_VERSION}`,
    );
  }
  if (!document?.components?.schemas) {
    problems.push('the document carries no component schemas');
  }
  if (!document?.paths || Object.keys(document.paths).length === 0) {
    problems.push('the document carries no paths');
  }
  return problems;
}

/** Compares every held schema against its interface, both directions. */
export function compare(document, typesSource) {
  const problems = [];
  for (const held of HELD_SCHEMAS) {
    const contractFields = schemaProperties(document, held.schema);
    if (contractFields === null) {
      problems.push(`the contract defines no schema ${held.schema}`);
      continue;
    }
    const interfaceFields = interfaceProperties(typesSource, held.interface);
    if (interfaceFields === null) {
      problems.push(`this repository declares no interface ${held.interface}`);
      continue;
    }
    const allowed = new Set(held.mayOmit);
    for (const field of contractFields) {
      if (!interfaceFields.has(field) && !allowed.has(field)) {
        problems.push(
          `${held.interface} cannot read ${held.schema}.${field}, which the contract defines`,
        );
      }
    }
    for (const field of interfaceFields) {
      if (!contractFields.has(field)) {
        problems.push(
          `${held.interface}.${field} is not defined by ${held.schema}, so nothing will ever send it`,
        );
      }
    }
  }
  return problems;
}

async function record(from) {
  const document = await readDocument(from);
  const problems = validateDocument(document);
  if (problems.length > 0) {
    fail(`Refusing to pin that document:\n  ${problems.join('\n  ')}`);
    return;
  }
  await writeFile(PINNED_PATH, `${JSON.stringify(document, null, 2)}\n`, 'utf8');
  process.stdout.write(
    `Pinned ${path.relative(REPOSITORY_ROOT, PINNED_PATH)} from ${from}\n`,
  );
}

async function check() {
  let document;
  try {
    document = JSON.parse(await readFile(PINNED_PATH, 'utf8'));
  } catch {
    fail(
      `Missing or unreadable ${path.relative(REPOSITORY_ROOT, PINNED_PATH)}. Record it with:\n` +
        '  node scripts/universe/portfolio-contract.mjs --record --from <url or file>',
    );
    return;
  }
  const typesSource = await readFile(TYPES_PATH, 'utf8');
  const problems = [
    ...validateDocument(document),
    ...compare(document, typesSource),
  ];
  if (problems.length > 0) {
    fail(
      `The portfolio contract and this repository disagree:\n  ${problems.join('\n  ')}\n\n` +
        'Re-record the contract, then bring the interfaces to it.',
    );
    return;
  }
  process.stdout.write(
    `Portfolio contract gate passed: ${HELD_SCHEMAS.length} schemas match their interfaces.\n`,
  );
}

async function main() {
  const argv = process.argv.slice(2);
  if (argv.includes('--record')) {
    const index = argv.indexOf('--from');
    const from = index === -1 ? null : argv[index + 1];
    if (!from) {
      fail('--record needs --from <url or file>');
      return;
    }
    await record(from);
    return;
  }
  if (argv.includes('--check')) {
    await check();
    return;
  }
  process.stdout.write(
    'usage: portfolio-contract.mjs --check | --record --from <url or file>\n',
  );
}

const invokedDirectly =
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) {
  main().catch((error) => {
    process.stderr.write(`${error instanceof Error ? error.message : error}\n`);
    process.exitCode = 1;
  });
}
